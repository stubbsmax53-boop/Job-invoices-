@app.route("/invoice/<int:invoice_id>", methods=["GET", "POST"])
@admin_required
def invoice_page(invoice_id: int):
    invoice = invoice_or_404(invoice_id)
    if request.method == "POST":
        try:
            amount = parse_amount(request.form.get("amount"))
        except ValueError as exc:
            flash(str(exc), "error")
            return redirect(url_for("invoice_page", invoice_id=invoice_id))
        db = get_db()
        db.execute(
            "UPDATE invoices SET amount = ?, updated_at = ? WHERE id = ?",
            (amount, now_iso(), invoice_id),
        )
        db.commit()
        flash("Amount saved.", "ok")
        return redirect(url_for("invoice_page", invoice_id=invoice_id))
    return render_template("invoice.html", invoice=invoice)


@app.route("/invoice/<int:invoice_id>/status", methods=["POST"])
@admin_required
def set_status(invoice_id: int):
    invoice_or_404(invoice_id)
    status = (request.form.get("status") or "").strip().lower()
    if status not in {"draft", "sent", "paid"}:
        flash("Invalid status.", "error")
        return redirect(url_for("invoice_page", invoice_id=invoice_id))
    db = get_db()
    db.execute(
        "UPDATE invoices SET status = ?, updated_at = ? WHERE id = ?",
        (status, now_iso(), invoice_id),
    )
    db.commit()
    flash(f"Marked as {status.capitalize()}.", "ok")
    return redirect(url_for("invoice_page", invoice_id=invoice_id))


@app.route("/invoice/<int:invoice_id>/send")
@admin_required
def send_invoice(invoice_id: int):
    """Redirect to a prefilled mailto: link. Nothing is sent automatically."""
    invoice = invoice_or_404(invoice_id)
    amount = format_money(invoice["amount"])
    date = format_local(invoice["created_at"], "%B %d, %Y")
    subject = f"Invoice {invoice['invoice_number']} for {invoice['address']}"
    body = (
        f"Invoice {invoice['invoice_number']}\n"
        f"Date: {date}\n"
        f"Job address: {invoice['address']}\n"
        f"Work performed: {invoice['description']}\n"
        f"Technician: {invoice['tech_name']}\n"
        f"Amount: {amount}\n"
        f"Status: {invoice['status'].capitalize()}\n"
    )
    mailto = f"mailto:?subject={quote(subject)}&body={quote(body)}"
    return redirect(mailto)


@app.route("/export.csv")
@admin_required
def export_csv():
    invoices = get_db().execute(
        "SELECT * FROM invoices ORDER BY id DESC"
    ).fetchall()
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(
        [
            "invoice_number",
            "date",
            "address",
            "description",
            "tech_name",
            "amount",
            "status",
        ]
    )
    for inv in invoices:
        writer.writerow(
            [
                inv["invoice_number"],
                format_local(inv["created_at"], "%Y-%m-%d"),
                inv["address"],
                inv["description"],
                inv["tech_name"],
                inv["amount"] or "",
                inv["status"],
            ]
        )
    return Response(
        buf.getvalue(),
        mimetype="text/csv",
        headers={
            "Content-Disposition": "attachment; filename=invoices.csv",
        },
    )


@app.route("/invoice/<int:invoice_id>/pdf")
@admin_required
def invoice_pdf(invoice_id: int):
    invoice = invoice_or_404(invoice_id)
    buf = io.BytesIO()
    build_pdf(buf, invoice)
    buf.seek(0)
    filename = f"{invoice['invoice_number']}.pdf"
    return Response(
        buf.getvalue(),
        mimetype="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={filename}"},
    )


def build_pdf(buf: io.BytesIO, invoice: AttrRow) -> None:
    name = app.config["BUSINESS_NAME"]
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
        title=f"Invoice {invoice['invoice_number']}",
        author=name,
    )
    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "InvTitle",
        parent=styles["Heading1"],
        fontName="Times-Bold",
        fontSize=22,
        textColor=colors.HexColor("#1a1a1a"),
        spaceAfter=2,
    )
    muted = ParagraphStyle(
        "Muted",
        parent=styles["Normal"],
        fontName="Times-Roman",
        fontSize=10,
        textColor=colors.HexColor("#555555"),
        leading=14,
    )
    body = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontName="Times-Roman",
        fontSize=11,
        textColor=colors.HexColor("#1a1a1a"),
        leading=16,
    )
    label = ParagraphStyle(
        "Label",
        parent=styles["Normal"],
        fontName="Times-Bold",
        fontSize=9,
        textColor=colors.HexColor("#666666"),
        spaceBefore=12,
        spaceAfter=2,
        tracking=1,
    )
    amount_style = ParagraphStyle(
        "Amount",
        parent=styles["Normal"],
        fontName="Times-Bold",
        fontSize=16,
        textColor=colors.HexColor("#1a1a1a"),
    )

    date = format_local(invoice["created_at"], "%B %d, %Y")
    status = invoice["status"].capitalize()
    amount = format_money(invoice["amount"])

    story = [
        Paragraph("INVOICE", title),
        Paragraph(f"{name}", muted),
        Spacer(1, 16),
    ]
    meta = Table(
        [
            [
                Paragraph(f"<b>Invoice</b><br/>{invoice['invoice_number']}", body),
                Paragraph(f"<b>Date</b><br/>{date}", body),
                Paragraph(f"<b>Status</b><br/>{status}", body),
            ]
        ],
        colWidths=[2.3 * inch, 2.3 * inch, 2.3 * inch],
    )
    meta.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#dddddd")),
            ]
        )
    )
    story += [
        meta,
        Paragraph("JOB ADDRESS", label),
        Paragraph(invoice["address"].replace("\n", "<br/>"), body),
        Paragraph("DESCRIPTION OF WORK", label),
        Paragraph(invoice["description"].replace("\n", "<br/>"), body),
        Paragraph("TECHNICIAN", label),
        Paragraph(invoice["tech_name"], body),
        Spacer(1, 18),
        Paragraph("AMOUNT DUE", label),
        Paragraph(amount if amount != "—" else "Amount not yet set", amount_style),
    ]
    doc.build(story)


