def normalize_database_url(url: str) -> str:
    """Render/Heroku may provide postgres://; psycopg wants postgresql://."""
    url = url.strip()
    if url.startswith("postgres://"):
        return "postgresql://" + url[len("postgres://") :]
    return url


def database_url() -> str | None:
    url = os.environ.get("DATABASE_URL", "").strip()
    return normalize_database_url(url) if url else None


class AttrRow:
    """Mapping + attribute access, matching sqlite3.Row in templates and views."""

    def __init__(self, data: Any) -> None:
        if isinstance(data, AttrRow):
            mapping = dict(data._data)
        elif isinstance(data, dict):
            mapping = dict(data)
        else:
            mapping = {key: data[key] for key in data.keys()}
        object.__setattr__(self, "_data", mapping)

    def __getitem__(self, key: str | int) -> Any:
        if isinstance(key, int):
            return list(self._data.values())[key]
        return self._data[key]

    def __getattr__(self, key: str) -> Any:
        try:
            return self._data[key]
        except KeyError as exc:
            raise AttributeError(key) from exc

    def keys(self) -> Iterable[str]:
        return self._data.keys()


class Database:
    def __init__(self, conn: Any, kind: str) -> None:
        self.conn = conn
        self.kind = kind  # "postgres" or "sqlite"

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Any:
        if self.kind == "postgres":
            sql = sql.replace("?", "%s")
        cursor = self.conn.execute(sql, tuple(params))
        return CursorAdapter(cursor)

    def commit(self) -> None:
        self.conn.commit()

    def rollback(self) -> None:
        self.conn.rollback()

    def close(self) -> None:
        self.conn.close()


class CursorAdapter:
    def __init__(self, cursor: Any) -> None:
        self.cursor = cursor
        self.lastrowid = getattr(cursor, "lastrowid", None)

    def fetchone(self) -> AttrRow | None:
        row = self.cursor.fetchone()
        return None if row is None else AttrRow(row)

    def fetchall(self) -> list[AttrRow]:
        return [AttrRow(row) for row in self.cursor.fetchall()]


def connect_db() -> Database:
    url = database_url()
    if url:
        import psycopg
        from psycopg.rows import dict_row

        conn = psycopg.connect(url, row_factory=dict_row)
        return Database(conn, "postgres")
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    # Autocommit so create_invoice can take an immediate write lock.
    conn.isolation_level = None
    return Database(conn, "sqlite")


