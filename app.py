@app.route("/", methods=["GET", "POST"])
def intake():
    errors = {}
    values = {"address": "", "description": "", "tech_name": ""}
    if request.method == "POST":
        values = {
            "address": (request.form.get("address") or "").strip(),
            "description": (request.form.get("description") or "").strip(),
            "tech_name": (request.form.get("tech_name") or "").strip(),
        }
        for field, label in (
            ("address", "Job address"),
            ("description", "Description of work"),
            ("tech_name", "Tech name"),
        ):
            if not values[field]:
                errors[field] = f"{label} is required."
        if not errors:
            invoice_id = create_invoice(get_db(), values)
            return redirect(url_for("thanks", invoice_id=invoice_id))
    return render_template("intake.html", errors=errors, values=values)


