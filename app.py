def get_db() -> Database:
    if "db" not in g:
        g.db = connect_db()
    return g.db


@app.teardown_appcontext
def close_db(_exc: BaseException | None) -> None:
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db() -> None:
    last_error: Exception | None = None
    attempts = 8 if database_url() else 1
    for attempt in range(1, attempts + 1):
        try:
            db = connect_db()
            try:
                db.execute(POSTGRES_SCHEMA if db.kind == "postgres" else SQLITE_SCHEMA)
                db.commit()
            finally:
                db.close()
            return
        except Exception as exc:  # pragma: no cover - retry around first-boot races
            last_error = exc
            if attempt == attempts:
                break
            time.sleep(min(2 * attempt, 10))
    if last_error is not None:
        raise last_error


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def parse_iso(value: str) -> datetime:
    return datetime.fromisoformat(value)


def format_local(value: str, fmt: str = "%b %d, %Y") -> str:
    dt = parse_iso(value)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(LOCAL_TZ).strftime(fmt)


def format_money(amount: str | None) -> str:
    if amount in (None, ""):
        return "—"
    try:
        return f"${Decimal(amount):,.2f}"
    except (InvalidOperation, ValueError):
        return "—"


def parse_amount(raw: str | None) -> str | None:
    if raw is None:
        return None
    cleaned = raw.strip().replace(",", "").replace("$", "")
    if cleaned == "":
        return None
    try:
        value = Decimal(cleaned)
    except InvalidOperation as exc:
        raise ValueError("Enter a valid dollar amount.") from exc
    if value < 0:
        raise ValueError("Amount cannot be negative.")
    return f"{value.quantize(Decimal('0.01'))}"


def next_invoice_number(db: Database) -> str:
    row = db.execute(
        "SELECT MAX(CAST(SUBSTR(invoice_number, 5) AS INTEGER)) AS n FROM invoices"
    ).fetchone()
    n = int((row["n"] if row and row["n"] is not None else 0) + 1)
    return f"INV-{n:04d}"


def create_invoice(db: Database, values: dict[str, str]) -> int:
    """Insert a job and return its id, assigning INV-0001... under a write lock."""
    now = now_iso()
    try:
        if db.kind == "postgres":
            db.execute("LOCK TABLE invoices IN SHARE ROW EXCLUSIVE MODE")
        else:
            db.execute("BEGIN IMMEDIATE")
        invoice_number = next_invoice_number(db)
        row = db.execute(
            """
            INSERT INTO invoices (
                invoice_number, address, description, tech_name,
                amount, status, created_at, updated_at
            ) VALUES (?, ?, ?, ?, NULL, 'draft', ?, ?)
            RETURNING id
            """,
            (
                invoice_number,
                values["address"],
                values["description"],
                values["tech_name"],
                now,
                now,
            ),
        ).fetchone()
        db.commit()
    except Exception:
        db.rollback()
        raise
    if row is None:
        raise RuntimeError("Failed to create invoice.")
    return int(row["id"])


def invoice_or_404(invoice_id: int) -> AttrRow:
    row = get_db().execute(
        "SELECT * FROM invoices WHERE id = ?", (invoice_id,)
    ).fetchone()
    if row is None:
        from flask import abort

        abort(404)
    return row


def admin_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        password = app.config["ADMIN_PASSWORD"]
        if password and not session.get("admin_ok"):
            session["next"] = request.path
            return redirect(url_for("login"))
        return view(*args, **kwargs)

    return wrapped


