def schema_statements(kind: str) -> list[str]:
    if kind == "postgres":
        tables = [POSTGRES_SCHEMA, CONTACTS_POSTGRES, MESSAGES_POSTGRES]
    else:
        tables = [SQLITE_SCHEMA, CONTACTS_SQLITE, MESSAGES_SQLITE]
    return [*tables, *MESSAGE_INDEXES, *jobs.tables(kind)]


def init_db() -> None:
    """Create missing tables. Safe to re-run against a database that already has invoices."""
    last_error: Exception | None = None
    attempts = 8 if database_url() else 1
    for attempt in range(1, attempts + 1):
        db: Database | None = None
        try:
            db = connect_db()
            for statement in schema_statements(db.kind):
                db.execute(statement)
            jobs.migrate(db)
            db.commit()
            return
        except Exception as exc:  # pragma: no cover - retry around first-boot races
            last_error = exc
            if db is not None:
                try:
                    db.rollback()
                except Exception:
                    pass
            if attempt == attempts:
                break
            time.sleep(min(2 * attempt, 10))
        finally:
            if db is not None:
                db.close()
    if last_error is not None:
        raise last_error


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def parse_iso(value: str) -> datetime:
    return datetime.fromisoformat(value)


def format_local(value: str, fmt: str = "%b %d, %Y") -> str:
    dt = parse_iso(value)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(LOCAL_TZ).strftime(fmt)


def format_money(amount: str | None) -> str:
    if amount in (None, ""):
        return "—"
    try:
        return f"${Decimal(amount):,.2f}"
    except (InvalidOperation, ValueError):
        return "—"


def parse_amount(raw: str | None) -> str | None:
    return jobs.parse_amount(raw)


def format_day(value: str | None, fmt: str = "%b %d, %Y") -> str:
    """Format a calendar date without shifting it across a timezone."""
    if not value:
        return "—"
    try:
        day = datetime.strptime(str(value)[:10], "%Y-%m-%d")
    except ValueError:
        return str(value)
    return day.strftime(fmt)


def _optional_job_id(value: Any) -> int | None:
    if value is None or value is False or isinstance(value, bool) or value == "":
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


