@app.route("/admin/messages", methods=["GET", "POST"])
@admin_required
def messages_page():
    if request.method == "POST":
        text = request.form.get("text") or ""
        if not text.strip():
            flash("Paste a message first.", "error")
            return redirect(url_for("messages_page"))
        result = ingest_inbound(
            get_db(),
            create_invoice,
            source="manual",
            sender=request.form.get("sender") or "",
            raw_text=text,
            subject=request.form.get("subject") or "",
        )
        settle_message(result.message_id, result.invoice_id)
        _log_intake("manual", result)
        if result.status == "created" and result.invoice_number:
            flash(f"Job {result.invoice_number} created from that message.", "ok")
        elif result.error:
            flash(result.error, "error")
        else:
            flash("Message saved.", "ok")
        return redirect(url_for("message_detail", message_id=result.message_id))

    status_filter = (request.args.get("status") or "").strip()
    if status_filter not in {"created", "needs_review", "failed"}:
        status_filter = ""
    db = get_db()
    if status_filter:
        messages = db.execute(
            MESSAGE_WITH_INVOICE + " WHERE m.status = ? ORDER BY m.id DESC",
            (status_filter,),
        ).fetchall()
    else:
        messages = db.execute(
            MESSAGE_WITH_INVOICE + " ORDER BY m.id DESC"
        ).fetchall()
    needs = db.execute(
        "SELECT COUNT(*) AS n FROM messages WHERE status = 'needs_review'"
    ).fetchone()
    return render_template(
        "messages.html",
        cards=[_message_card(row) for row in messages],
        status_filter=status_filter,
        needs_review=int(needs["n"] or 0) if needs else 0,
    )


@app.route("/admin/messages/<int:message_id>", methods=["GET", "POST"])
@admin_required
def message_detail(message_id: int):
    db = get_db()
    row = db.execute(
        MESSAGE_WITH_INVOICE + " WHERE m.id = ?",
        (message_id,),
    ).fetchone()
    if row is None:
        abort(404)
    contact = _contact_for(row)
    errors: dict[str, str] = {}
    form_values = prefill_form(row, contact)
    hints = form_values.get("hints") or []
    if request.method == "POST":
        outcome = apply_corrections(db, create_invoice, message_id, request.form)
        if outcome is None:
            abort(404)
        if outcome.ok:
            settle_message(message_id, outcome.invoice_id)
            if outcome.invoice_number:
                flash(f"Job {outcome.invoice_number} created.", "ok")
            else:
                flash("Job created.", "ok")
            return redirect(url_for("message_detail", message_id=message_id))
        errors = outcome.errors
        form_values = outcome.values
        hints = []
        row = db.execute(
            MESSAGE_WITH_INVOICE + " WHERE m.id = ?",
            (message_id,),
        ).fetchone()
        contact = _contact_for(row)
    related = []
    if row is not None and row["contact_id"]:
        related = db.execute(
            """
            SELECT id, source, status, received_at, invoice_id
            FROM messages
            WHERE contact_id = ? AND id != ?
            ORDER BY id DESC
            LIMIT 8
            """,
            (row["contact_id"], row["id"]),
        ).fetchall()
    parsed = ParsedMessage.from_json(row["parsed_json"]).to_dict() if row else {}
    linked_job = None
    if row is not None and row["job_id"]:
        linked_job = jobs.get_job(db, int(row["job_id"]))
    return render_template(
        "message.html",
        message=row,
        parsed=parsed,
        contact=contact,
        related=related,
        errors=errors,
        form_values=form_values,
        hints=hints,
        linked_job=linked_job,
        board_jobs=jobs.list_jobs(db),
    )


def _contact_for(row: AttrRow | None):
    if row is None or not row["contact_id"]:
        return None
    return get_db().execute(
        "SELECT * FROM contacts WHERE id = ?",
        (row["contact_id"],),
    ).fetchone()


