def _provided_intake_tokens() -> list[str]:
    tokens: list[str] = []
    header = (request.headers.get("X-Intake-Token") or "").strip()
    if header:
        tokens.append(header)
    auth = request.headers.get("Authorization") or ""
    if auth.lower().startswith("bearer "):
        bearer = auth[7:].strip()
        if bearer:
            tokens.append(bearer)
    query = (request.args.get("token") or "").strip()
    if query:
        tokens.append(query)
    return tokens


def intake_secret_status() -> str:
    """Return ok, unconfigured, or forbidden. The token is optional until it is set."""
    expected = os.environ.get("INTAKE_WEBHOOK_TOKEN", "").strip()
    if not expected:
        return "unconfigured"
    for token in _provided_intake_tokens():
        if len(token) == len(expected) and secrets.compare_digest(token, expected):
            return "ok"
    return "forbidden"


def _intake_auth_error(status: str):
    if status == "unconfigured":
        return (
            jsonify(
                {
                    "ok": False,
                    "error": "Intake webhook is not configured. Set INTAKE_WEBHOOK_TOKEN.",
                }
            ),
            503,
        )
    return jsonify({"ok": False, "error": "Invalid intake token."}), 403


def webhook_denied():
    status = intake_secret_status()
    if status == "ok":
        return None
    return _intake_auth_error(status)


def api_denied():
    """JSON intake accepts the shared token or an admin session."""
    if intake_secret_status() == "ok" or session.get("admin_ok"):
        return None
    return _intake_auth_error(intake_secret_status())


def twilio_denied():
    """Validate X-Twilio-Signature only when TWILIO_AUTH_TOKEN is set."""
    auth_token = os.environ.get("TWILIO_AUTH_TOKEN", "").strip()
    if not auth_token:
        return None
    signature = request.headers.get("X-Twilio-Signature", "")
    params = request.form.to_dict(flat=True) if request.form else {}
    if not twilio_signature_valid(request.url, params, signature, auth_token):
        app.logger.warning("Rejected an SMS webhook with an invalid Twilio signature.")
        return jsonify({"ok": False, "error": "Invalid Twilio signature."}), 403
    return None


def _request_mapping() -> dict:
    if request.is_json:
        data = request.get_json(silent=True) or {}
        return data if isinstance(data, dict) else {}
    if request.form:
        return request.form.to_dict(flat=True)
    raw = request.get_data(as_text=True) or ""
    if raw.lstrip().startswith("{"):
        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            return {}
        return data if isinstance(data, dict) else {}
    return {}


def _intake_json(result):
    return jsonify(
        {
            "ok": True,
            "duplicate": result.duplicate,
            "message_id": result.message_id,
            "status": result.status,
            "invoice_id": result.invoice_id,
            "invoice_number": result.invoice_number,
            "error": result.error,
        }
    )


def _stamp_intake_headers(response: Response, result) -> None:
    response.headers["X-Intake-Status"] = result.status
    response.headers["X-Intake-Message-Id"] = str(result.message_id)
    if result.invoice_id:
        response.headers["X-Intake-Invoice-Id"] = str(result.invoice_id)
    if result.duplicate:
        response.headers["X-Intake-Duplicate"] = "1"


def _log_intake(source: str, result) -> None:
    app.logger.info(
        "intake source=%s status=%s message_id=%s invoice_id=%s duplicate=%s",
        source,
        result.status,
        result.message_id,
        result.invoice_id,
        result.duplicate,
    )


