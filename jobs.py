def list_activity(
    db: Any,
    *,
    reviewed: bool | None = None,
    job_id: int | None = None,
    limit: int = 200,
) -> list[Any]:
    clauses: list[str] = []
    params: list[Any] = []
    if reviewed is not None:
        clauses.append("a.reviewed = ?")
        params.append(1 if reviewed else 0)
    if job_id is not None:
        clauses.append("a.job_id = ?")
        params.append(job_id)
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    safe_limit = max(1, min(int(limit), 500))
    params.append(safe_limit)
    return db.execute(
        f"""
        SELECT a.*, j.customer AS job_customer, j.job_name AS job_name,
               j.town AS job_town, j.street_address AS job_street,
               m.invoice_id AS invoice_id, i.invoice_number AS invoice_number
        FROM activity a
        LEFT JOIN jobs j ON j.id = a.job_id
        LEFT JOIN messages m ON m.id = a.message_id
        LEFT JOIN invoices i ON i.id = m.invoice_id
        {where}
        ORDER BY a.received_at DESC, a.id DESC
        LIMIT ?
        """,
        tuple(params),
    ).fetchall()


