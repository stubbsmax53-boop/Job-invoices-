def record_activity(
    db: Any,
    *,
    source: str,
    summary: str,
    sender: str = "",
    body: str = "",
    address: str = "",
    job_id: int | None = None,
    message_id: int | None = None,
    external_id: str | None = None,
    received_at: str | None = None,
) -> dict[str, Any]:
    """Store one inbox row. New rows are unreviewed. A repeated external id returns the first row."""
    external_id = (external_id or "").strip()[:255] or None
    if external_id:
        existing = db.execute(
            "SELECT id FROM activity WHERE external_id = ?",
            (external_id,),
        ).fetchone()
        if existing:
            return activity_to_dict(_activity_row(db, int(existing["id"])), duplicate=True)
    if job_id is None and address:
        matched = find_job_by_address(db, address)
        if matched is not None:
            job_id = int(matched["id"])
    if job_id is not None and get_job(db, int(job_id)) is None:
        raise LookupError("Unknown job.")
    received = received_at or now_iso()
    try:
        row = db.execute(
            """
            INSERT INTO activity (
                source, sender, summary, body, address, reviewed,
                job_id, message_id, external_id, received_at, reviewed_at
            ) VALUES (?, ?, ?, ?, ?, 0, ?, ?, ?, ?, NULL)
            RETURNING id
            """,
            (
                source,
                sender or None,
                summary,
                body or None,
                address or None,
                int(job_id) if job_id else None,
                int(message_id) if message_id else None,
                external_id,
                received,
            ),
        ).fetchone()
        db.commit()
    except Exception as exc:
        db.rollback()
        if external_id and _is_unique_violation(exc):
            existing = db.execute(
                "SELECT id FROM activity WHERE external_id = ?",
                (external_id,),
            ).fetchone()
            if existing:
                return activity_to_dict(_activity_row(db, int(existing["id"])), duplicate=True)
        if message_id and _is_unique_violation(exc):
            existing = db.execute(
                "SELECT id FROM activity WHERE message_id = ?",
                (int(message_id),),
            ).fetchone()
            if existing:
                return activity_to_dict(_activity_row(db, int(existing["id"])), duplicate=True)
        raise
    if row is None:
        raise RuntimeError("Failed to store activity.")
    return activity_to_dict(_activity_row(db, int(row["id"])), duplicate=False)


