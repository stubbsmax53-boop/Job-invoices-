def list_jobs(
    db: Any,
    *,
    status: str | None = None,
    customer: str | None = None,
    week: bool = False,
    today: date | None = None,
) -> list[Any]:
    clauses: list[str] = []
    params: list[Any] = []
    if status:
        clauses.append("status = ?")
        params.append(status)
    if customer:
        clauses.append("customer = ?")
        params.append(customer)
    if week:
        start, end = week_bounds(today)
        clauses.append(
            """
            (
                (start_date IS NOT NULL AND start_date >= ? AND start_date <= ?)
                OR (target_finish IS NOT NULL AND target_finish >= ? AND target_finish <= ?)
                OR (
                    start_date IS NOT NULL AND target_finish IS NOT NULL
                    AND start_date <= ? AND target_finish >= ?
                )
            )
            """
        )
        params.extend([start, end, start, end, end, start])
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    if week:
        order = " ORDER BY COALESCE(start_date, target_finish, '9999-99-99'), id DESC"
    else:
        order = " ORDER BY id DESC"
    rows = db.execute(f"SELECT * FROM jobs{where}{order}", tuple(params)).fetchall()
    if week:
        return rows
    return sorted(rows, key=lambda row: (_STATUS_RANK.get(row["status"], 99), row["start_date"] or "9999-99-99", -int(row["id"])))


def list_customers(db: Any) -> list[str]:
    rows = db.execute(
        "SELECT DISTINCT customer FROM jobs WHERE customer != '' ORDER BY customer"
    ).fetchall()
    return [row["customer"] for row in rows]


