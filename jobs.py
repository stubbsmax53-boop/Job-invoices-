def migrate(db: Any) -> None:
    """Add job links to existing invoices and messages. Safe to re-run."""
    _add_column(db, "invoices", "job_id", "INTEGER")
    _add_column(db, "messages", "job_id", "INTEGER")
    for statement in _INDEXES:
        db.execute(statement)


def _add_column(db: Any, table: str, column: str, ddl: str) -> None:
    if table not in {"invoices", "messages"}:
        raise ValueError(f"Refusing to alter {table}.")
    if column in _column_names(db, table):
        return
    db.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")


def _column_names(db: Any, table: str) -> set[str]:
    if table not in {"invoices", "messages", "jobs", "material_orders", "activity", "job_needs"}:
        raise ValueError(f"Refusing to inspect {table}.")
    if db.kind == "postgres":
        rows = db.execute(
            """
            SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = ?
            """,
            (table,),
        ).fetchall()
        return {row["name"] for row in rows}
    rows = db.execute(f"PRAGMA table_info({table})").fetchall()
    return {row["name"] for row in rows}


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def today_local(today: date | None = None) -> date:
    if today is not None:
        return today
    return datetime.now(LOCAL_TZ).date()


def week_bounds(today: date | None = None) -> tuple[str, str]:
    """Monday through Sunday in America/Denver, as YYYY-MM-DD."""
    day = today_local(today)
    start = day - timedelta(days=day.weekday())
    end = start + timedelta(days=6)
    return start.isoformat(), end.isoformat()


def parse_amount(raw: Any) -> str | None:
    if raw is None or isinstance(raw, bool):
        return None
    if isinstance(raw, (int, float, Decimal)):
        cleaned = format(Decimal(str(raw)), "f")
    else:
        cleaned = str(raw).strip().replace(",", "").replace("$", "")
    if cleaned == "":
        return None
    try:
        value = Decimal(cleaned)
    except InvalidOperation as exc:
        raise ValueError("Enter a valid dollar amount.") from exc
    if value < 0:
        raise ValueError("Amount cannot be negative.")
    return f"{value.quantize(Decimal('0.01'))}"


def reject_time_tracking(payload: dict | None) -> str | None:
    """Return an error when a payload tries to store hours or clock times."""
    if not isinstance(payload, dict):
        return None
    found = [str(key) for key in payload if str(key).strip().lower() in TIME_KEYS]
    if not found:
        return None
    return "Crew is paid per job. Send a job amount instead of hours."


