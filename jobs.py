def validate_job(payload: dict) -> tuple[dict[str, Any], dict[str, str]]:
    errors: dict[str, str] = {}
    customer = _clip(payload.get("customer"), 160)
    job_name = _clip(payload.get("job_name"), 200)
    street = re.sub(r"\s+", " ", _clip(payload.get("street_address"), 300))
    town = re.sub(r"\s+", " ", _clip(payload.get("town"), 120))
    status = _clip(payload.get("status") or "lead", 40).lower().replace(" ", "_").replace("/", "_")
    if status == "tape":
        status = "tape_finish"
    crew = _clip(payload.get("crew"), 300)
    notes = _clip(payload.get("notes"), 8000)
    if not customer:
        errors["customer"] = "Customer is required."
    if not job_name:
        errors["job_name"] = "Job name is required."
    if not street:
        errors["street_address"] = "Street address is required."
    if status not in _STATUS_KEYS:
        errors["status"] = "Choose a status from Lead through Paid."
        status = "lead"
    try:
        start_date = _parse_date(payload.get("start_date"), "Start date")
    except ValueError as exc:
        errors["start_date"] = str(exc)
        start_date = None
    try:
        target_finish = _parse_date(payload.get("target_finish"), "Target finish")
    except ValueError as exc:
        errors["target_finish"] = str(exc)
        target_finish = None
    amount = None
    if "amount" in payload and payload.get("amount") not in (None, ""):
        try:
            amount = parse_amount(payload.get("amount"))
        except ValueError as exc:
            errors["amount"] = str(exc)
    if start_date and target_finish and target_finish < start_date:
        errors["target_finish"] = "Target finish is on or after the start date."
    clean = {
        "customer": customer,
        "job_name": job_name,
        "street_address": street,
        "town": town,
        "status": status,
        "crew": crew,
        "start_date": start_date,
        "target_finish": target_finish,
        "amount": amount,
        "notes": notes,
    }
    return clean, errors


