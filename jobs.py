def _parse_date(value: Any, label: str) -> str | None:
    if value is None:
        return None
    if isinstance(value, bool):
        raise ValueError(f"{label} must be a calendar date (YYYY-MM-DD).")
    if isinstance(value, datetime):
        raise ValueError(f"{label} must be a calendar date (YYYY-MM-DD).")
    if isinstance(value, date):
        return value.isoformat()
    text = str(value).strip()
    if text == "":
        return None
    if not _DATE_RE.fullmatch(text):
        raise ValueError(f"{label} must be a calendar date (YYYY-MM-DD).")
    try:
        datetime.strptime(text, "%Y-%m-%d")
    except ValueError as exc:
        raise ValueError(f"{label} must be a real calendar date.") from exc
    return text


def _parse_received(value: Any) -> str:
    if isinstance(value, bool) or value is None:
        raise ValueError("Received time must be an ISO timestamp.")
    text = str(value).strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError as exc:
        raise ValueError("Received time must be an ISO timestamp.") from exc
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).isoformat()


def _clip(value: Any, limit: int) -> str:
    if value is None or isinstance(value, bool):
        return ""
    return str(value).strip()[:limit]


def _is_int(value: Any) -> bool:
    if isinstance(value, bool) or value is None or isinstance(value, float):
        return False
    if isinstance(value, int):
        return True
    return bool(re.fullmatch(r"-?\d+", str(value).strip()))


def _is_unique_violation(exc: BaseException) -> bool:
    current: BaseException | None = exc
    seen: set[int] = set()
    while current is not None and id(current) not in seen:
        seen.add(id(current))
        if current.__class__.__name__ in {"IntegrityError", "UniqueViolation"}:
            return True
        current = current.__cause__
    return False
