def money_sum(amounts: list[Any]) -> str | None:
    total = Decimal("0")
    saw = False
    for amount in amounts:
        if amount in (None, ""):
            continue
        try:
            total += Decimal(str(amount))
        except InvalidOperation:
            continue
        saw = True
    if not saw:
        return None
    return f"{total.quantize(Decimal('0.01'))}"


def find_job_by_address(db: Any, address: str) -> Any:
    """Return the newest job whose street matches. Different unit numbers do not match."""
    street, town = split_street_town(address)
    if not street_parts(street)[0]:
        return None
    rows = db.execute(
        "SELECT * FROM jobs ORDER BY updated_at DESC, id DESC"
    ).fetchall()
    matches = []
    for job in rows:
        job_street, street_town = split_street_town(job["street_address"] or "")
        if not streets_match(job_street, street):
            continue
        job_town = clean_town(job["town"] or street_town)
        incoming_town = clean_town(town)
        if incoming_town and job_town and not towns_compatible(incoming_town, job_town):
            continue
        matches.append(job)
    if not matches:
        return None
    incoming_town = clean_town(town)
    if incoming_town:
        town_hits = []
        for job in matches:
            _street, street_town = split_street_town(job["street_address"] or "")
            job_town = clean_town(job["town"] or street_town)
            if job_town and towns_compatible(incoming_town, job_town):
                town_hits.append(job)
        if town_hits:
            return town_hits[0]
    return matches[0]


def split_street_town(address: str) -> tuple[str, str]:
    parts = [part.strip() for part in (address or "").split(",") if part.strip()]
    if not parts:
        return "", ""
    if len(parts) == 1:
        return parts[0], ""
    return parts[0], clean_town(parts[1])


def clean_town(value: str) -> str:
    text = re.sub(r"\s+", " ", (value or "").strip())
    text = re.sub(r"\s+\d{5}(?:-\d{4})?$", "", text)
    text = re.sub(r"\s+[A-Za-z]{2}$", "", text)
    return text.strip(" ,")


def towns_compatible(left: str, right: str) -> bool:
    a = clean_town(left).casefold()
    b = clean_town(right).casefold()
    if not a or not b:
        return True
    return a == b


def street_parts(value: str) -> tuple[str, str]:
    text = (value or "").lower().replace(".", " ")
    text = text.replace("#", " # ")
    text = re.sub(r"[,/]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    unit_match = _UNIT_RE.search(text)
    unit = ""
    if unit_match:
        unit = re.sub(r"[^a-z0-9]", "", unit_match.group(0).lower())
        text = (text[: unit_match.start()] + " " + text[unit_match.end() :]).strip()
        text = re.sub(r"\s+", " ", text)
    words = []
    for word in text.split():
        mapped = _DIRECTION_MAP.get(word, word)
        words.append(_SUFFIX_MAP.get(mapped, mapped))
    return " ".join(words), unit


def streets_match(left: str, right: str) -> bool:
    left_street, left_unit = street_parts(left)
    right_street, right_unit = street_parts(right)
    if not left_street or not right_street or left_street != right_street:
        return False
    if left_unit and right_unit and left_unit != right_unit:
        return False
    return True


def joined_address(street: str, town: str) -> str:
    street = (street or "").strip()
    town = (town or "").strip()
    if street and town:
        return f"{street}, {town}"
    return street or town


def settle_inbound(
    db: Any,
    *,
    message_id: int | None,
    invoice_id: int | None,
) -> int | None:
    """Link an inbound message to a board job and make sure the inbox has a row."""
    job_id = None
    if invoice_id:
        job_id = attach_inbound_job(db, int(invoice_id))
        rows = db.execute(
            "SELECT id FROM messages WHERE invoice_id = ?",
            (int(invoice_id),),
        ).fetchall()
        for row in rows:
            ensure_activity_for_message(db, int(row["id"]), job_id)
        return job_id
    if message_id:
        job_id = link_message_by_address(db, int(message_id))
        ensure_activity_for_message(db, int(message_id), job_id)
    return job_id


def attach_inbound_job(db: Any, invoice_id: int) -> int | None:
    """Use the job already at this street, or open one lead. Crew is left blank."""
    invoice = db.execute("SELECT * FROM invoices WHERE id = ?", (invoice_id,)).fetchone()
    if invoice is None:
        return None
    if invoice["job_id"]:
        _link_invoice_messages(db, invoice_id, int(invoice["job_id"]))
        db.commit()
        return int(invoice["job_id"])
    prior = db.execute(
        """
        SELECT job_id FROM messages
        WHERE invoice_id = ? AND job_id IS NOT NULL
        ORDER BY id
        LIMIT 1
        """,
        (invoice_id,),
    ).fetchone()
    matched = find_job_by_address(db, invoice["address"] or "")
    if prior and prior["job_id"]:
        job_id = int(prior["job_id"])
    elif matched is not None:
        job_id = int(matched["id"])
    else:
        job_id = create_job(db, _job_from_invoice(db, invoice))
    db.execute(
        "UPDATE invoices SET job_id = ?, updated_at = ? WHERE id = ? AND job_id IS NULL",
        (job_id, now_iso(), invoice_id),
    )
    _link_invoice_messages(db, invoice_id, job_id)
    db.commit()
    return job_id


def link_message_by_address(db: Any, message_id: int) -> int | None:
    message = db.execute("SELECT * FROM messages WHERE id = ?", (message_id,)).fetchone()
    if message is None:
        return None
    if message["job_id"]:
        return int(message["job_id"])
    address = _message_address(message)
    if not address:
        return None
    matched = find_job_by_address(db, address)
    if matched is None:
        return None
    job_id = int(matched["id"])
    db.execute(
        "UPDATE messages SET job_id = ? WHERE id = ? AND job_id IS NULL",
        (job_id, message_id),
    )
    db.commit()
    return job_id


def ensure_activity_for_message(db: Any, message_id: int, job_id: int | None) -> None:
    message = db.execute("SELECT * FROM messages WHERE id = ?", (message_id,)).fetchone()
    if message is None:
        return
    existing = db.execute(
        "SELECT * FROM activity WHERE message_id = ?",
        (message_id,),
    ).fetchone()
    if existing:
        if job_id and not existing["job_id"]:
            db.execute(
                "UPDATE activity SET job_id = ? WHERE id = ?",
                (int(job_id), int(existing["id"])),
            )
            db.commit()
        return
    parsed = ParsedMessage.from_json(message["parsed_json"])
    address = parsed.address or extract_address(message["raw_text"] or "")
    who = parsed.client_name or message["sender"] or "Unknown sender"
    label = source_label(message["source"])
    text = re.sub(r"\s+", " ", (message["raw_text"] or "").strip())
    summary = f"{label} from {who}"
    if text:
        summary = f"{summary}: {_clip(text, 180)}"
    record_activity(
        db,
        source=message["source"] or "manual",
        sender=message["sender"] or "",
        summary=_clip(summary, 500),
        body=message["raw_text"] or "",
        address=address,
        job_id=int(job_id) if job_id else None,
        message_id=message_id,
        received_at=message["received_at"] or now_iso(),
    )


