def describe_order(job: Any, order: dict[str, Any], *, previous: Any = None) -> str:
    name = describe_job(job)
    item = order["item"]
    if order.get("qty"):
        item = f"{order['qty']} {item}"
    if previous is not None and previous["delivery_date"] != order.get("delivery_date") and order.get("delivery_date"):
        return f"Delivery scheduled: {item} for {name} on {order['delivery_date']}"
    if previous is None and order.get("delivery_date"):
        return f"Delivery scheduled: {item} for {name} on {order['delivery_date']}"
    if previous is not None and previous["status"] != order.get("status"):
        label = order_status_label(order.get("status"))
        return f"Material {label.lower()}: {item} for {name}"
    if previous is None:
        return f"Material ordered: {item} for {name}"
    return f"Material order updated: {item} for {name}"


def _job_from_invoice(db: Any, invoice: Any) -> dict[str, Any]:
    message = db.execute(
        "SELECT * FROM messages WHERE invoice_id = ? ORDER BY id DESC LIMIT 1",
        (int(invoice["id"]),),
    ).fetchone()
    parsed = ParsedMessage.from_json(message["parsed_json"]) if message else ParsedMessage()
    street, town = split_street_town(invoice["address"] or "")
    customer = _clip(parsed.client_name, 160) or "Inbound"
    description = invoice["description"] or ""
    first = description.split("\n\n", 1)[0]
    first = re.sub(r"\s+", " ", first).strip()
    job_name = _clip(first, 120) or "Inbound job"
    return {
        "customer": customer,
        "job_name": job_name,
        "street_address": street or (invoice["address"] or "Address"),
        "town": town,
        "status": "lead",
        "crew": "",
        "start_date": None,
        "target_finish": None,
        "amount": None,
        "notes": description,
    }


