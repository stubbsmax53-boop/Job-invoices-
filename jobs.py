def list_orders(
    db: Any,
    *,
    job_id: int | None = None,
    status: str | None = None,
    open_only: bool = False,
) -> list[Any]:
    clauses: list[str] = []
    params: list[Any] = []
    if job_id is not None:
        clauses.append("o.job_id = ?")
        params.append(job_id)
    if status:
        clauses.append("o.status = ?")
        params.append(status)
    if open_only:
        clauses.append("o.status != 'stocked'")
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    return db.execute(
        f"""
        SELECT o.*, j.customer AS job_customer, j.job_name AS job_name,
               j.town AS job_town, j.street_address AS job_street
        FROM material_orders o
        JOIN jobs j ON j.id = o.job_id
        {where}
        ORDER BY COALESCE(o.delivery_date, o.order_date, '9999-99-99'), o.id
        """,
        tuple(params),
    ).fetchall()


