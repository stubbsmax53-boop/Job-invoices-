def validate_activity(payload: dict) -> tuple[dict[str, Any], dict[str, str]]:
    """Assistant posts are stored unreviewed. ``reviewed`` in the body is ignored."""
    errors: dict[str, str] = {}
    summary = _clip(payload.get("summary"), 500)
    body = _clip(payload.get("body"), 8000)
    sender = _clip(payload.get("sender"), 500)
    address = re.sub(r"\s+", " ", _clip(payload.get("address"), 300))
    external_id = _clip(payload.get("external_id"), 255)
    source_raw = payload.get("source")
    if source_raw is None or str(source_raw).strip() == "":
        source = "assistant"
    else:
        source = str(source_raw).strip().lower()
    if not _SOURCE_RE.fullmatch(source):
        errors["source"] = "Use a short source such as assistant, sms, or email."
        source = "assistant"
    if not summary:
        errors["summary"] = "Summary is required."
    received_at = now_iso()
    if payload.get("received_at") not in (None, ""):
        try:
            received_at = _parse_received(payload.get("received_at"))
        except ValueError as exc:
            errors["received_at"] = str(exc)
    job_id = None
    if payload.get("job_id") not in (None, ""):
        if isinstance(payload.get("job_id"), bool) or not _is_int(payload.get("job_id")):
            errors["job_id"] = "job_id must be a job on the board."
        else:
            job_id = int(payload.get("job_id"))
    return (
        {
            "source": source,
            "sender": sender,
            "summary": summary,
            "body": body,
            "address": address,
            "external_id": external_id or None,
            "received_at": received_at,
            "job_id": job_id,
            "reviewed": 0,
        },
        errors,
    )


